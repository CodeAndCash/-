def template_script(niche: str, purpose: str, variant: int = 0) -> str:
    """Запасной скрипт, если нейросеть недоступна или лимит исчерпан."""
    rng = random.Random(variant * 7919 + 13)
    base = _TEMPLATES.get(purpose, _TEMPLATES["first"])
    hi = GREETINGS[variant % len(GREETINGS)] if variant else GREETINGS[0]
    close = rng.choice(CLOSERS)
    hi_call = ["Здравствуйте!", "Добрый день!"][variant % 2]
    return base.format(
        hi=hi, hi_call=hi_call, close=close, niche=_clean(niche, 60) or "[ваша ниша]"
    )


def make_title(purpose: str, niche: str) -> str:
    title = PURPOSES.get(purpose, PURPOSES["first"])[0]
    niche = _clean(niche, 40)
    return f"{title} — {niche}"[:80] if niche else title[:80]
