def _vars(niche: int) -> dict:
    data = dict(_NICHE_TEXT.get(niche, _NICHE_TEXT[1]))
    data["site_offer_cap"] = data["site_offer"][:1].upper() + data["site_offer"][1:]
    data["bot_offer_low"] = data["bot_offer"][:1].lower() + data["bot_offer"][1:]
    return data


