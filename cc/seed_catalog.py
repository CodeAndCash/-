def _install_npx(repo: str, skill: str, codex: bool) -> str:
    cmd = f"npx skills add {repo} --skill {skill}" + (" --agent codex" if codex else "")
    return f"""## Как поставить
В терминале, в папке проекта:

```bash
{cmd}
```

{CODEX_NPX_NOTE if codex else CLAUDE_NOTE}"""


def skill(codex, slug, group, name, sub, desc, when, repo, free=0, skill_name=None, more=""):
    author = repo.split("/")[0]
    body = f"""{desc}
{more}
## Когда брать
{when}

{_install_npx(repo, skill_name or name, codex)}

## Откуда
Автор: `{author}`. [Исходник на GitHub](https://github.com/{repo}). {SOURCE_NOTE}"""
    return dict(slug=slug, kind="cskill" if codex else "skill", module=group, title=name, subtitle=sub, body=body,
                icon="bolt", free=free, minutes=2)


def openai_skill(slug, group, name, sub, desc, when, free=0, system=False):
    if system:
        install = f"""## Как включить
Скилл встроен в Codex — ставить ничего не нужно. Вызови его явно: напиши `${name}` в запросе или выбери через `/skills`."""
    else:
        install = f"""## Как поставить
Внутри Codex (в чате или CLI) напиши:

```text
$skill-installer {name}
```

Скилл установится в `~/.codex/skills/` и будет работать во всех проектах. Если не появился в `/skills` — перезапусти Codex."""
    body = f"""{desc}

## Когда брать
{when}

{install}

## Откуда
Официальный каталог скиллов OpenAI для Codex. [Исходник на GitHub](https://github.com/openai/skills)."""
    return dict(slug=slug, kind="cskill", module=group, title=name, subtitle=sub, body=body, icon="bolt", free=free, minutes=2)


